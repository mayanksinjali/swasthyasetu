export function initialAppState(): AppState {
  const cases = buildCases().map((caseItem) =>
    caseItem.status === 'new'
      ? caseItem
      : { ...caseItem, priority: computePriority(caseItem, FACILITIES, DEMO_EPOCH) },
  )
  return {
    demoNow: DEMO_EPOCH,
    cases,
    facilities: FACILITIES,
    transportResources: TRANSPORT_RESOURCES,
    timeline: buildTimeline(),
  }
}
